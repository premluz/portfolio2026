import assert from 'node:assert/strict';
import {initEnvironment} from '../dist/environment.js';
const saved=new Map(),elements=new Map(),themeListeners=[];
const node=()=>({dataset:{},style:{setProperty(){}},classList:{toggle(){}},setAttribute(k,v){this[k]=v;},value:'',hidden:false});
const choices=['dark','light','system'].map(value=>Object.assign(node(),{dataset:{themeChoice:value}}));
const root=node();root.classList={add(){},remove(){}};
globalThis.document={documentElement:root,body:node(),getElementById(id){if(!elements.has(id))elements.set(id,node());return elements.get(id);},querySelectorAll(){return choices;}};
globalThis.localStorage={getItem:k=>saved.get(k),setItem:(k,v)=>saved.set(k,v)};
globalThis.window={addEventListener(){}};
const media={matches:false,addEventListener(type,fn){themeListeners.push(fn);}};globalThis.matchMedia=()=>media;
initEnvironment();
assert.equal(root.dataset.theme,'light');
choices[2].onclick();assert.equal(root.dataset.themePreference,'system');assert.equal(saved.get('prem-theme'),'system');
media.matches=true;themeListeners[0]();assert.equal(root.dataset.theme,'dark');assert.equal(choices[2]['aria-pressed'],'true');
choices[1].onclick();media.matches=false;themeListeners[0]();media.matches=true;themeListeners[0]();assert.equal(root.dataset.theme,'light','An explicit theme ignores OS changes');
elements.get('themeToggle').onclick();assert.equal(root.dataset.theme,'dark');assert.equal(saved.get('prem-theme'),'dark');
elements.get('themeToggle').onclick();assert.equal(root.dataset.themePreference,'system','The single icon reaches System after Dark');
elements.get('themeToggle').onclick();assert.equal(root.dataset.themePreference,'light','Theme cycles back to Light');
console.log('Site theme passed: explicit modes, live System preference, persistence and control synchronization.');
