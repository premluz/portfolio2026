// Re-encodes catalog MP4s into smaller H.264 copies; the originals stay canonical, as with images.
// A copy is kept only when it is smaller; otherwise the manifest records no URL and the original is served.
import {execFileSync} from 'node:child_process';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {catalogVideos,readVideoVariants,sha1} from './video-freshness.mjs';

// CRF 24 measured SSIM >= 0.996 against the originals for bastion, porter and rios (screen recordings).
const CRF='24',PRESET='slow',AUDIO_BITRATE='96k',HASH_LENGTH=8;
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),dist=path.join(root,'dist');
const output=path.join(dist,'assets/optimised');

try{execFileSync('ffmpeg',['-version'],{stdio:'ignore'});}
catch(error){throw new Error('optimise-videos needs ffmpeg on PATH (brew install ffmpeg)',{cause:error});}
await fs.mkdir(output,{recursive:true});

const previous=await readVideoVariants(root),manifest={};
let before=0,after=0;
for(const asset of await catalogVideos(root)){
 const source=path.join(dist,asset.url);
 if(!await fs.access(source).then(()=>true,()=>false))continue;
 const digest=await sha1(source),old=previous[asset.url];
 const size=(await fs.stat(source)).size;before+=size;
 if(old?.source===digest&&(!old.url||await fs.access(path.join(dist,old.url)).then(()=>true,()=>false))){
  manifest[asset.url]=old;after+=old.url?(await fs.stat(path.join(dist,old.url))).size:size;continue;
 }
 // The source hash in the name gives a replaced video a new URL, so browsers and CDNs cannot serve the old one.
 const target=path.join(output,`${path.parse(source).name}-${digest.slice(0,HASH_LENGTH)}.mp4`);
 execFileSync('ffmpeg',['-v','error','-y','-i',source,'-map','0:v:0','-map','0:a:0?','-c:v','libx264','-preset',PRESET,'-crf',CRF,'-pix_fmt','yuv420p','-c:a','aac','-b:a',AUDIO_BITRATE,'-movflags','+faststart',target],{stdio:['ignore','inherit','inherit']});
 const encoded=(await fs.stat(target)).size;
 if(old?.url&&path.join(dist,old.url)!==target)await fs.rm(path.join(dist,old.url),{force:true});
 if(encoded>=size){await fs.rm(target);manifest[asset.url]={source:digest,url:null};after+=size;continue;}
 manifest[asset.url]={source:digest,url:path.relative(dist,target).split(path.sep).join('/')};after+=encoded;
}
await fs.writeFile(path.join(dist,'video-variants.js'),'// Generated by scripts/optimise-videos.mjs. Original media remains canonical.\nexport const videoVariants='+JSON.stringify(manifest)+';\n');
console.log(`Optimised ${Object.values(manifest).filter(entry=>entry.url).length} of ${Object.keys(manifest).length} videos: ${after.toLocaleString()} bytes served vs ${before.toLocaleString()} original bytes.`);
