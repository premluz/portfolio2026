"""Build responsive WebP copies; keep the original portfolio media intact."""
from pathlib import Path
import json
from io import BytesIO
from PIL import Image, ImageOps

root = Path(__file__).resolve().parent.parent
output = root / "dist/assets/optimised"
output.mkdir(parents=True, exist_ok=True)
manifest = {}
before = after = 0
for asset in json.loads((root / "content/catalog.json").read_text())["assets"]:
    if asset["type"] != "image" or not asset["url"].startswith("assets/"):
        continue
    source = root / "dist" / asset["url"]
    if not source.is_file():
        continue
    # Vectors scale without raster variants, and Pillow cannot decode them.
    if source.suffix.lower() == ".svg":
        continue
    with Image.open(source) as raw:
        source_image = ImageOps.exif_transpose(raw)
        has_alpha = "A" in source_image.getbands() and source_image.getchannel("A").getextrema() != (255, 255)
        image = source_image.convert("RGBA" if has_alpha else "RGB")
        width, height = image.size
        candidates = sorted(set([min(width, value) for value in (480, 960, 1440, 1920)]))
        variants = []
        for size in candidates:
            target = output / f"{source.stem}-{size}.webp"
            resized = image.resize((size, max(1, round(height * size / width))), Image.Resampling.LANCZOS)
            encoded = BytesIO()
            resized.save(encoded, "WEBP", quality=90, method=6)
            payload = encoded.getvalue()
            if len(payload) < 12:
                raise RuntimeError(f"Empty WebP output for {source}")
            with Image.open(BytesIO(payload)) as verification:
                verification.verify()
            target.write_bytes(payload)
            variants.append({"url": target.relative_to(root / "dist").as_posix(), "width": size})
        manifest[asset["url"]] = {"width": width, "height": height, "variants": variants}
        before += source.stat().st_size
        after += (root / "dist" / variants[-1]["url"]).stat().st_size
(root / "dist/image-variants.js").write_text("// Generated by scripts/optimise-images.py. Original media remains canonical.\nexport const imageVariants=" + json.dumps(manifest, separators=(",", ":")) + ";\n")
print(f"Built responsive WebP copies for {len(manifest)} images: largest variants {after:,} bytes vs {before:,} original bytes.")
