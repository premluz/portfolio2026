import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {contentModel,exportPublishedCatalog} from '../dist/content/model.js';
import {answerSchema,createContentStore} from '../dist/content/provider.js';
import {DEFAULT_CONTENT_SET} from '../dist/content/content-set.js';
import {prepareCatalog,readAssistantData} from '../dist/content/assistant-data.js';
import {contentSetNames,contentSourceLabel,readContentSource} from './content-source.mjs';
import {posterRatioMismatches,withMeasuredMedia} from './media-metadata.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const check=process.argv.includes('--check');
// Every content/catalog*.json file or content/catalog*/ folder is a content set; all ship in one deploy and share the same media.
const sets=await contentSetNames(path.join(root,'content'));
if(!sets.includes(DEFAULT_CONTENT_SET))throw new Error(`content/${DEFAULT_CONTENT_SET}/ (or content/${DEFAULT_CONTENT_SET}.json) is required as the default content set.`);
const json=value=>JSON.stringify(value,null,2)+'\n';
// Assistant-only data is shared by every content set; a missing file just means none yet.
let assistant;
try{assistant=JSON.parse(await fs.readFile(path.join(root,'content/assistant.json'),'utf8'));}
catch(error){if(error.code!=='ENOENT')throw new Error('Cannot read content/assistant.json',{cause:error});}
const assistantIds=Object.keys(readAssistantData(assistant)),knownIds=new Set();
const files={
 'schema.json':json(contentModel.schema),
 'response.schema.json':json(answerSchema),
 'sets.js':`// Generated by scripts/build-content.mjs from the content/catalog* sets.\nexport const contentSets=${JSON.stringify(sets)};\n`
};
const counts=[];
for(const set of sets){
 const catalog=await withMeasuredMedia(await readContentSource(path.join(root,'content'),set),path.join(root,'dist'));
 const source=await contentSourceLabel(path.join(root,'content'),set);
 for(const doc of catalog.documents)knownIds.add(doc.id);
 const published=exportPublishedCatalog(prepareCatalog(catalog,assistant)),store=createContentStore(published);
 // Check local media before deployment, as well as identity/type references.
 for(const asset of published.assets){if(!/^https?:\/\//.test(asset.url))await fs.access(path.join(root,'dist',decodeURIComponent(asset.url.split(/[?#]/)[0])));}
 files[`${set}.js`]=`// Generated by scripts/build-content.mjs; edit ${source}.\nexport const catalog=`+json(published).trimEnd()+';\n';
 files[`${set}.json`]=json(published);
 if(set===DEFAULT_CONTENT_SET)files['index.json']=json({schemaVersion:1,documents:store.list().map(d=>({id:d.id,type:d.type,title:d.title,pageTitle:d.pageTitle||d.title,summary:d.summary||'',domains:d.domains||[],capabilities:d.capabilities||[],tags:d.tags||[],kind:d.kind||null,client:d.client||null,evidenceIds:(d.evidence||[]).map(e=>e.id)}))});
 counts.push(`${set}: ${published.documents.length} documents, ${published.assets.length} assets`);
 for(const line of posterRatioMismatches(published))console.warn(`Poster/video ratio differs by more than 1% (${set}): ${line}`);
}
const orphans=assistantIds.filter(id=>!knownIds.has(id));
if(orphans.length)throw new Error(`content/assistant.json names documents no content set has: ${orphans.join(', ')}`);
for(const [name,content] of Object.entries(files)){
 const target=path.join(root,'dist/content',name);
 if(check){if(await fs.readFile(target,'utf8').catch(()=>null)!==content)throw new Error('Stale generated content: '+name);}else await fs.writeFile(target,content);
}
console.log(`${check?'Checked':'Built'} content v1 (${counts.join('; ')}).`);
