import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {contentModel,exportPublishedCatalog} from '../dist/content/model.js';
import {answerSchema,createContentStore} from '../dist/content/provider.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const catalog=JSON.parse(await fs.readFile(path.join(root,'content/catalog.json'),'utf8'));
const published=exportPublishedCatalog(catalog),store=createContentStore(published);
// Check local media before deployment, as well as identity/type references.
for(const asset of published.assets){if(!/^https?:\/\//.test(asset.url))await fs.access(path.join(root,'dist',decodeURIComponent(asset.url.split(/[?#]/)[0])));}
const json=value=>JSON.stringify(value,null,2)+'\n';
const files={
 'catalog.js':'// Generated by scripts/build-content.mjs; edit content/catalog.json.\nexport const catalog='+json(published).trimEnd()+';\n',
 'catalog.json':json(published),
 'schema.json':json(contentModel.schema),
 'response.schema.json':json(answerSchema),
 'index.json':json({schemaVersion:1,documents:store.list().map(d=>({id:d.id,type:d.type,title:d.title,pageTitle:d.pageTitle||d.title,summary:d.summary||'',domains:d.domains||[],capabilities:d.capabilities||[],tags:d.tags||[],kind:d.kind||null,client:d.client||null,evidenceIds:(d.evidence||[]).map(e=>e.id)}))})
};
for(const [name,content] of Object.entries(files)){
 const target=path.join(root,'dist/content',name);
 if(process.argv.includes('--check')){if(await fs.readFile(target,'utf8').catch(()=>null)!==content)throw new Error('Stale generated content: '+name);}else await fs.writeFile(target,content);
}
console.log(`${process.argv.includes('--check')?'Checked':'Built'} content v${published.schemaVersion}: ${published.documents.length} documents, ${published.assets.length} assets.`);
