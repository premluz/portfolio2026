import fs from 'node:fs/promises';
import path from 'node:path';

// content/knowledge.json is the source of the approved profile facts and curated answers. Two modules are generated
// from it so every importer keeps working: dist/knowledge/profile.js and dist/assistant-knowledge.js.
const isText=value=>typeof value==='string'&&value.trim()!=='';
const isTexts=value=>Array.isArray(value)&&value.length>0&&value.every(isText);

export async function readKnowledge(root){
 const file=path.join(root,'content/knowledge.json');
 try{return JSON.parse(await fs.readFile(file,'utf8'));}
 catch(error){throw new Error(`Cannot read ${file}`,{cause:error});}
}

// publishedIdsBySet: Map of content set name -> Set of published document ids. A source must be published in every set.
export function validateKnowledge(knowledge,publishedIdsBySet){
 const problems=[],ids=new Set();
 if(knowledge?.version!==1)problems.push('version must be 1');
 if(!isTexts(knowledge?.suggestedQuestions))problems.push('suggestedQuestions must be a non-empty list of text');
 const checkRecord=(kind,record,required)=>{
  const label=`${kind} ${record?.id??'(no id)'}`;
  if(!isText(record?.id))problems.push(`${label} needs an id`);
  else if(ids.has(record.id))problems.push(`${label} duplicates an id`);
  else ids.add(record.id);
  for(const field of required.text)if(!isText(record?.[field]))problems.push(`${label} needs ${field}`);
  for(const field of required.lists)if(!isTexts(record?.[field]))problems.push(`${label} needs a non-empty ${field} list`);
  if(!Array.isArray(record?.sourceIds)||!record.sourceIds.length)return;
  for(const [set,published] of publishedIdsBySet)for(const id of record.sourceIds)if(!published.has(id))problems.push(`${label} names source ${id}, which is not a published document in ${set}`);
 };
 if(!Array.isArray(knowledge?.facts))problems.push('facts must be a list');
 for(const fact of knowledge?.facts||[])checkRecord('fact',fact,{text:['title','topic','text','route'],lists:['sourceIds','tags']});
 if(!Array.isArray(knowledge?.answers))problems.push('answers must be a list');
 for(const answer of knowledge?.answers||[])checkRecord('answer',answer,{text:['text'],lists:['phrases','sourceIds','followUps']});
 if(problems.length)throw new Error(`content/knowledge.json is invalid:\n- ${problems.join('\n- ')}`);
}

// Generated modules, keyed by path under dist/. Values are exactly what the earlier hand-written modules exported.
export function knowledgeModules(knowledge){
 const json=value=>JSON.stringify(value,null,1);
 return {
  'knowledge/profile.js':`// Generated by scripts/build-content.mjs from content/knowledge.json; edit that file.\nexport const profileFacts=${json(knowledge.facts)};\n`,
  'assistant-knowledge.js':`// Generated by scripts/build-content.mjs from content/knowledge.json; edit that file.\n// Curated answers are offline recovery copy, not a replacement for model synthesis.\nimport {profileFacts} from './knowledge/profile.js';\nimport {createKnowledgeLookup,normalizeAssistantPhrase} from './assistant-knowledge-lookup.js';\nexport const assistantKnowledge={\n version:${json(knowledge.version)},\n facts:profileFacts,\n answers:${json(knowledge.answers)},\n suggestedQuestions:${json(knowledge.suggestedQuestions)},\n};\nexport {normalizeAssistantPhrase};\nexport const {findCuratedAnswer,suggestionsFor}=createKnowledgeLookup(assistantKnowledge);\n`
 };
}
